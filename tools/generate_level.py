"""Deterministic reference-style T-maze; emits Dart and JSON maps."""
import json
from pathlib import Path
W,H=60,45
empty={(x,y) for y in range(10,15) for x in range(10,44)} | {(x,y) for y in range(15,45) for x in range(17,20)}
walls={(nx,ny) for x,y in empty for nx,ny in ((x+1,y),(x-1,y),(x,y+1),(x,y-1)) if 0<=nx<W and 0<=ny<H and (nx,ny) not in empty}
walls-={(16,44),(20,44)}
walls|={(0,0),(1,0),(2,0),(57,0),(58,0),(59,0),(0,44),(1,44),(58,44)}
power={(5,39),(28,39),(50,40),(55,31),(4,29),(45,24),(4,18),(49,16),(34,7),(22,6),(56,7),(3,6)}
assert len(empty)==260 and len(walls)==140 and len(power)==12
rows=[]
for y in range(H):
    line=''
    for x in range(W):
        p=(x,y)
        line+=('.' if p in empty else '#' if p in walls else 'P' if p in power else 'G' if (x*17+y*23)%191==0 else 'B')
    rows.append(line)
assert sum(c in 'BGP' for line in rows for c in line)==2300
root=Path(__file__).resolve().parents[1]
(root/'assets/level_desert_gate.json').write_text(json.dumps({'id':'desert_gate_01','version':2,'width':W,'height':H,'rows':rows},indent=2)+'\n')
src="""// GENERATED by tools/generate_level.py. B/G/P breakable; # metal; . empty.
class DesertGateLevel {
  static const id = 'desert_gate_01';
  static const version = 2;
  static const columns = 60;
  static const rows = 45;
  static const totalPixels = 2300;
  static const map = <String>[\n"""+''.join("    '"+r+"',\n" for r in rows)+"  ];\n}\n"
(root/'lib/game/level_data.dart').write_text(src)
print('Generated reference-style T maze and 2300 breakable pixels.')
